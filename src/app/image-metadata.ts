import { MobiansImage } from 'src/_shared/mobians-image.interface';

/**
 * The prompt and settings written into a downloaded PNG's text chunks (see
 * BlobMigrationService.embedPngTextMetadata). Shared by every place an image is downloaded, so a
 * file saved from a result is the same as one saved from history.
 */
export function buildImageMetadata(image: MobiansImage): Record<string, string> {
  const meta: Record<string, string> = {};
  meta['model'] = image.model ? `Mobians.ai / ${image.model}` : 'Mobians.ai';
  meta['Disclaimer'] = 'The image is generated by Mobians.ai. The image is not real and is generated by an AI.';
  if (image.prompt) meta['prompt'] = image.prompt;
  if (image.negativePrompt) meta['negative_prompt'] = image.negativePrompt;
  if (image.seed != null) meta['seed'] = String(image.seed);
  if (image.cfg != null) meta['cfg'] = String(image.cfg);
  if (image.editProvenance) meta['edit_provenance'] = JSON.stringify(image.editProvenance);

  if (Array.isArray(image.loras) && image.loras.length > 0) {
    meta['loras'] = image.loras
      .map((l: any) => `${l.name} - ${l.version} - strength: ${l.strength}`)
      .join('\n');
  }

  const rp = image.regional_prompting;
  if (rp?.enabled && Array.isArray(rp.regions) && rp.regions.length > 0) {
    if (rp.version === 2) meta['regional_settings'] = `separation=${rp.separation ?? 'balanced'}, layout_hints=${rp.layout_hints === true}`;
    meta['regional_prompting'] = rp.regions.map((r: any, i: number) => {
      const parts = [`Region ${i + 1}${r.name ? ` (${r.name})` : ''}: prompt="${r.prompt || ''}"`];
      if (r.negative_prompt) parts.push(`negative_prompt="${r.negative_prompt}"`);
      parts.push(`x=${r.x ?? 0}, y=${r.y ?? 0}, w=${r.width ?? 0}, h=${r.height ?? 0}`);
      // Version 2 strength; version 1 entries meant denoise_strength x opacity.
      const strength = r.strength ?? (r.denoise_strength ?? 1) * (r.opacity ?? 1);
      parts.push(`strength=${strength}, feather=${r.feather ?? 0}`);
      if (r.inherit_base_prompt) parts.push('inherit_base_prompt=true');
      return parts.join(', ');
    }).join('\n');
  }

  return meta;
}
